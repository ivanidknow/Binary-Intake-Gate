STUB_TEMPLATE = '''/*
 * MITRE {mitre_id} — minimal stub for Payload-as-Code matrix coverage.
 */
#include <windows.h>

static const char *mitre_id = "{mitre_id}";

int main(void) {{
    (void)mitre_id;
    return 0;
}}
'''


def main() -> None:
    TEMPLATES_DIR.mkdir(parents=True, exist_ok=True)
    existing = {f.stem for f in TEMPLATES_DIR.glob("*.c")}
    n = 0
    for i, mitre_id in enumerate(MITRE_IDS):
        safe = mitre_id.replace(".", "_").replace(" ", "_")[:40]
        test_id = f"mitre_stub_{i:03d}_{safe}"
        if test_id in existing:
            continue
        path = TEMPLATES_DIR / f"{test_id}.c"
        path.write_text(STUB_TEMPLATE.format(mitre_id=mitre_id), encoding="utf-8")
        n += 1
        if n >= 218:
            break
    print(f"Generated {n} stub templates in {TEMPLATES_DIR}")


if __name__ == "__main__":
    main()
